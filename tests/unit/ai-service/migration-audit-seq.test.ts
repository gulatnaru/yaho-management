import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const sql = readFileSync("prisma/migrations/20261115170000_ai_service_audit_seq/migration.sql", "utf8");
const previousSql = readFileSync("prisma/migrations/20261115160000_ai_service_audit_emergency_pause/migration.sql", "utf8");

describe("audit sequence migration contract", () => {
    it("adds only the identity column without destructive operations", () => {
        const statements = sql.replace(/--[^\n]*/g, "").split(";").map(statement => statement.trim()).filter(Boolean);
        expect(statements).toEqual([
            "BEGIN",
            "SET LOCAL lock_timeout = '5s'",
            "SET LOCAL statement_timeout = '60s'",
            'ALTER TABLE "AiServiceDeletionAudit" ADD COLUMN "seq" BIGINT GENERATED BY DEFAULT AS IDENTITY',
            "COMMIT",
        ]);
        expect(sql).not.toMatch(/\b(?:DROP|TRUNCATE|DELETE\s+FROM|UPDATE)\b/i);
    });
    it("leaves the CHECK, allowed values, guard trigger and functions unchanged", () => {
        expect(sql).not.toMatch(/\b(?:CHECK|CONSTRAINT|TRIGGER|FUNCTION)\b/i);
        expect(previousSql).toContain("'PREVIEW','PRODUCTION'");
        expect(previousSql).toContain("'DELETE_SINGLE','DELETE_BULK','READ_CONSULTATION','EMERGENCY_PAUSE'");
        expect(previousSql).toContain("'USER_REQUEST','ADMIN_REVIEW','ADMIN_READ','EMERGENCY_PAUSE'");
        expect(previousSql).toContain("'SINGLE','BULK','READ','CONFIG'");
    });
});
